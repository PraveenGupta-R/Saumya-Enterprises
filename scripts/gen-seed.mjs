// Generates worker/seed.sql from seed/seed.json.
// Idempotent: every INSERT is guarded by a 'seeded' marker row in `settings`, written last,
// so re-running never duplicates or resurrects content the owner deleted in the admin panel.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const seed = JSON.parse(readFileSync(join(root, 'seed', 'seed.json'), 'utf8'));

const q = (v) => `'${String(v ?? '').replace(/'/g, "''")}'`;
const j = (v) => q(JSON.stringify(v ?? []));
const b = (v) => (v ? 1 : 0);
const n = (v) => (Number.isFinite(Number(v)) ? Number(v) : 0);
const GUARD = `WHERE NOT EXISTS (SELECT 1 FROM settings WHERE key = 'seeded')`;

const out = ['-- GENERATED by scripts/gen-seed.mjs from seed/seed.json. Do not edit by hand.'];

out.push(`INSERT INTO settings (key, value) SELECT 'site', ${j(seed.settings)} ${GUARD};`);

for (const c of seed.categories) {
  out.push(
    `INSERT INTO categories (slug, name, description, sort) SELECT ${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${n(c.sort)} ${GUARD};`,
  );
}

for (const p of seed.products) {
  out.push(
    `INSERT INTO products (slug, category_id, name, short_desc, description, origin, availability, specs, sizes, grades, packaging, moq, supply_capacity, quality_standards, export_availability, images, seo_title, seo_description, sort, published)
SELECT ${q(p.slug)}, (SELECT id FROM categories WHERE slug = ${q(p.categorySlug)}), ${q(p.name)}, ${q(p.shortDesc)}, ${q(p.description)}, ${q(p.origin)}, ${q(p.availability)}, ${j(p.specs)}, ${j(p.sizes)}, ${j(p.grades)}, ${j(p.packaging)}, ${q(p.moq)}, ${q(p.supplyCapacity)}, ${j(p.qualityStandards)}, ${q(p.exportAvailability)}, ${j(p.images)}, ${q(p.seoTitle)}, ${q(p.seoDescription)}, ${n(p.sort)}, ${b(p.published)} ${GUARD};`,
  );
}

for (const c of seed.certifications) {
  out.push(
    `INSERT INTO certifications (key, name, status, note, sort, published) SELECT ${q(c.key)}, ${q(c.name)}, ${q(c.status)}, ${q(c.note)}, ${n(c.sort)}, ${b(c.published)} ${GUARD};`,
  );
}

for (const p of seed.posts) {
  out.push(
    `INSERT INTO posts (slug, title, excerpt, body, cover_url, published, published_at) SELECT ${q(p.slug)}, ${q(p.title)}, ${q(p.excerpt)}, ${q(p.body)}, ${q(p.coverUrl)}, ${b(p.published)}, ${q(p.publishedAt)} ${GUARD};`,
  );
}

for (const t of seed.testimonials) {
  out.push(
    `INSERT INTO testimonials (name, company, country, text, published, sort) SELECT ${q(t.name)}, ${q(t.company)}, ${q(t.country)}, ${q(t.text)}, ${b(t.published)}, ${n(t.sort)} ${GUARD};`,
  );
}

out.push(`INSERT OR IGNORE INTO settings (key, value) VALUES ('seeded', '1');`);

writeFileSync(join(root, 'worker', 'seed.sql'), out.join('\n') + '\n');
console.log('Wrote worker/seed.sql');
